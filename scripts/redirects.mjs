// Writes public/_redirects (Cloudflare Pages) from data/redirects.json.
// Old indexed URLs whose replacement post isn't live yet get a temporary 302 to
// the closest page; once the replacement passes QA and its pubDate has passed,
// the same URL becomes a permanent 301 to the new post. Runs before every build.
import fs from 'node:fs';
import path from 'node:path';
import { DATA_DIR, ROOT } from '../agents/lib/config.mjs';
import { listPosts, listTranslations } from '../agents/lib/store.mjs';
import { readQa } from '../agents/qa-agent.mjs';

const { redirects } = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'redirects.json'), 'utf8'));
const now = Date.now();
const live = new Set(
  listPosts()
    .filter((p) => !p.data.draft && Date.parse(p.data.pubDate) <= now && readQa(p.slug)?.pass)
    .map((p) => p.slug),
);

// ---- URL guard (owner rule: a published URL never 404s) --------------------------------------
// data/published-urls.json keeps every blog URL that has ever gone live. A URL whose post file is
// gone (merged, deleted or renamed) must have a redirect in data/redirects.json, or the build stops.
const LEDGER = path.join(DATA_DIR, 'published-urls.json');
const ledger = fs.existsSync(LEDGER) ? JSON.parse(fs.readFileSync(LEDGER, 'utf8')) : { urls: [] };
const files = new Set([
  ...listPosts().map((p) => `/blog/${p.slug}/`),
  ...listTranslations().map((p) => `/${p.lang}/blog/${p.slug}/`),
]);
const liveNow = [
  ...listPosts().filter((p) => !p.data.draft && Date.parse(p.data.pubDate) <= now).map((p) => `/blog/${p.slug}/`),
  ...listTranslations().filter((p) => !p.data.draft && Date.parse(p.data.pubDate) <= now).map((p) => `/${p.lang}/blog/${p.slug}/`),
];
const urls = [...new Set([...ledger.urls, ...liveNow])].sort();
if (urls.length !== ledger.urls.length) fs.writeFileSync(LEDGER, JSON.stringify({ _note: 'Every blog URL that has gone live. scripts/redirects.mjs adds new ones on each build; a URL whose post is gone needs a redirect in data/redirects.json.', urls }, null, 2) + '\n');
const norm = (u) => u.replace(/\/?$/, '/');
const redirected = new Set(redirects.map((r) => norm(r.from)));
const orphans = urls.filter((u) => !files.has(u) && !redirected.has(u));
if (orphans.length) {
  console.error(`✖ ${orphans.length} published URL(s) have no post and no redirect. Add a 301 to data/redirects.json (from → the merged or replacement post):`);
  for (const u of orphans) console.error('   ' + u);
  process.exit(1);
}
// Collapse chains (A → B → C becomes A → C) and flag redirects that point at a missing blog post.
const byFrom = new Map(redirects.map((r) => [norm(r.from), r]));
for (const r of redirects) {
  let to = r.to, hops = 0;
  while (byFrom.has(norm(to)) && hops++ < 5) to = byFrom.get(norm(to)).to;
  if (to !== r.to) { console.log(`redirect chain collapsed: ${r.from} → ${to} (was → ${r.to})`); r.to = to; }
  if (/^\/([a-z]{2}\/)?blog\/[^/]+\/?$/.test(r.to) && !files.has(norm(r.to)) && !r.pendingSlug) console.warn(`! redirect ${r.from} → ${r.to}: target post does not exist`);
}

const lines = ['# Generated by scripts/redirects.mjs from data/redirects.json. Do not edit by hand.'];
// Crawlers and audit tools often try /sitemap.xml first; the real index is /sitemap-index.xml.
lines.push('/sitemap.xml /sitemap-index.xml 301');
for (const r of redirects) {
  const ready = r.pendingSlug && live.has(r.pendingSlug);
  const to = ready ? `/blog/${r.pendingSlug}/` : r.to;
  const status = r.pendingSlug && !ready ? 302 : 301;
  const from = r.from.replace(/\/$/, '');
  lines.push(`${from} ${to} ${status}`, `${from}/ ${to} ${status}`);
}
fs.writeFileSync(path.join(ROOT, 'public/_redirects'), lines.join('\n') + '\n');
console.log(`_redirects: ${redirects.length} old URLs (${redirects.filter((r) => r.pendingSlug && !live.has(r.pendingSlug)).length} waiting for their new post)`);
