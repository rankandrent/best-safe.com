// Writes public/_redirects (Cloudflare Pages) from data/redirects.json.
// Old indexed URLs whose replacement post isn't live yet get a temporary 302 to
// the closest page; once the replacement passes QA and its pubDate has passed,
// the same URL becomes a permanent 301 to the new post. Runs before every build.
import fs from 'node:fs';
import path from 'node:path';
import { DATA_DIR, ROOT } from '../agents/lib/config.mjs';
import { listPosts } from '../agents/lib/store.mjs';
import { readQa } from '../agents/qa-agent.mjs';

const { redirects } = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'redirects.json'), 'utf8'));
const now = Date.now();
const live = new Set(
  listPosts()
    .filter((p) => !p.data.draft && Date.parse(p.data.pubDate) <= now && readQa(p.slug)?.pass)
    .map((p) => p.slug),
);

const lines = ['# Generated by scripts/redirects.mjs from data/redirects.json. Do not edit by hand.'];
// Crawlers and audit tools often try /sitemap.xml first; the real index is /sitemap-index.xml.
lines.push('/sitemap.xml /sitemap-index.xml 301');
for (const r of redirects) {
  const ready = r.pendingSlug && live.has(r.pendingSlug);
  const to = ready ? `/blog/${r.pendingSlug}/` : r.to;
  const status = r.pendingSlug && !ready ? 302 : 301;
  const from = r.from.replace(/\/$/, '');
  lines.push(`${from} ${to} ${status}`, `${from}/ ${to} ${status}`);
}
fs.writeFileSync(path.join(ROOT, 'public/_redirects'), lines.join('\n') + '\n');
console.log(`_redirects: ${redirects.length} old URLs (${redirects.filter((r) => r.pendingSlug && !live.has(r.pendingSlug)).length} waiting for their new post)`);
